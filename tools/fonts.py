"""Builds the two small display fonts shipped with the game (src/fonts/*.woff2 and src/fonts/fonts.css).

Only the characters used by titles, buttons, card names, races, sigils and skill names are kept (every CJK
character in index.html and src/js/*.js, plus cards.json), so the files stay small; question text keeps using
the system / Google font. Each font is then cut into three files with a unicode-range, so a browser downloads a
part only when the screen shows one of its characters:
  core  — the title screen's own text (tools/font-core.txt) and ASCII / punctuation
  cards — card names, races and sigils (the title, deck and duel screens)
  rest  — everything else (other screens, dialogs)

Re-run after adding cards or UI text:

    python3 tools/fonts.py <dir with NotoSerifTC.ttf and NotoSansTC.ttf (variable, from github.com/google/fonts)>

Without that directory it re-cuts the full subsets kept in tools/font-full/ (fine for moving characters between
parts, but new characters need the source fonts).
"""
import glob, io, json, os, re, sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
CJK = re.compile(r'[⺀-鿿豈-﫿＀-￯　-〿‐-‧←-⇿■-◿]')
FULL = os.path.join(HERE, 'font-full'); DST = os.path.join(ROOT, 'src/fonts')
FACES = [('FD Serif', 'fd-serif', 'NotoSerifTC.ttf', 500, 700), ('FD Sans', 'fd-sans', 'NotoSansTC.ttf', 500, 700)]

def card_chars():
    s = set()
    for c in json.load(open(os.path.join(ROOT, 'public/data/cards.json'), encoding='utf-8'))['cards']:
        s |= set(c['name'] + c['race'] + c['sigil'])
    return s

def charset():
    s = set()
    for f in [os.path.join(ROOT, 'index.html')] + glob.glob(os.path.join(ROOT, 'src/js/*.js')):
        s |= set(CJK.findall(open(f, encoding='utf-8').read()))
    s |= card_chars()
    s |= set(chr(i) for i in range(0x20, 0x7F)) | set('×−–—·•…％＋「」『』【】（）、。，：；！？～◆◇')
    return s

def cut(font_bytes, text, flavor='woff2'):
    f = TTFont(io.BytesIO(font_bytes))
    opt = subset.Options(); opt.layout_features = ['kern', 'liga', 'vert', 'vrt2', 'locl']; opt.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]; opt.notdef_outline = True
    sub = subset.Subsetter(opt); sub.populate(text=''.join(sorted(text))); sub.subset(f)
    f.flavor = flavor; out = io.BytesIO(); f.save(out); return out.getvalue()

def ranges(chars):
    cps = sorted(ord(c) for c in chars); out = []; i = 0
    while i < len(cps):
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1: j += 1
        out.append(f'U+{cps[i]:X}' if i == j else f'U+{cps[i]:X}-{cps[j]:X}'); i = j + 1
    return ','.join(out)

def main(src):
    os.makedirs(DST, exist_ok=True); os.makedirs(FULL, exist_ok=True)
    for old in glob.glob(os.path.join(DST, '*.woff2')): os.remove(old)
    want = charset()
    core = (set(open(os.path.join(HERE, 'font-core.txt'), encoding='utf-8').read().strip())
            | set(chr(i) for i in range(0x20, 0x7F)) | set('×−–—·•…％＋「」『』【】（）、。，：；！？～◆◇')) & want
    cards = (card_chars() & want) - core
    rest = want - core - cards
    css = ['/* generated by tools/fonts.py — do not edit by hand */']
    for family, name, ttf, lo, hi in FACES:
        full = os.path.join(FULL, name + '.woff2')
        if src:                                            # rebuild the full subset from the source font
            f = TTFont(io.BytesIO(cut(open(os.path.join(src, ttf), 'rb').read(), want, None)))
            f = instancer.instantiateVariableFont(f, {'wght': (lo, hi)})   # keep only the weights the game uses
            f.flavor = 'woff2'; f.save(full)
        data = open(full, 'rb').read()
        have = set(chr(c) for c in TTFont(io.BytesIO(data)).getBestCmap())
        for part, text in (('core', core), ('cards', cards), ('rest', rest)):
            text = text & have
            if not text: continue
            out = cut(data, text); open(os.path.join(DST, f'{name}-{part}.woff2'), 'wb').write(out)
            css.append(f'@font-face{{font-family:"{family}";src:url("./{name}-{part}.woff2") format("woff2");font-weight:{lo} {hi};font-display:swap;unicode-range:{ranges(text)}}}')
            print(f'{name}-{part}.woff2', len(text), 'chars', len(out) // 1024, 'KB')
    open(os.path.join(DST, 'fonts.css'), 'w', encoding='utf-8').write('\n'.join(css) + '\n')

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else None)
