/* lower the opponent's next attack / raise our own next attack, from whichever side is using the card */
function weaken(c, n) { if (c.side === 'p') G.mods.foeAtk -= n; else G.mods.myAtk -= n; }
function buff(c, n) { if (c.side === 'p') G.mods.myAtk += n; else G.mods.foeAtk += n; }
function skipNext(c) { if (c.side === 'p') G.mods.skipFoe = true; else G.mods.skipMe = true; }
/* raise DEF after a successful block: first cancels piercing damage, any surplus is reflected */
function addDef(c, n) { const net = c.reflect - c.pierce + n; c.reflect = Math.max(0, net); c.pierce = Math.max(0, -net); return true; }
function discard(side) {
  const h = G.hand[side]; if (!h.length) return;
  const [gone] = h.splice(Math.floor(Math.random() * h.length), 1);
  UI.renderHands();
  UI.floatText(side === 'p' ? $('#hand') : $('#cpu-hand'), `丟棄【${MON[gone.id].name}】`, 'small');
}
function drawExtra(side) {
  if (G.hand[side].length >= 6) return false;
  refillDeck(side);
  G.hand[side].push(G.deck[side].pop()); UI.renderHands(); return true;
}
async function skillFX(side, m) {
  const sk = SKILLS[m.id];
  Sound.skill();
  UI.floatText($('#slot-' + side), `【${sk.name}】`, 'skill');
  const slotCard = $('#slot-' + side + ' .card');
  if (slotCard && !RM) slotCard.animate([{ boxShadow: '0 0 0 0 #f3dc9500' }, { boxShadow: '0 0 0 4px #f3dc95, 0 0 30px 8px #d8b25a' }, { boxShadow: '0 0 0 0 #f3dc9500' }], { duration: 700 });
  UI.log(`${side === 'p' ? '' : '對手的'}<b>【${esc(m.name)}】</b>發動技能【${sk.name}】：${sk.text}`);
  await sleep(700);
}
async function heal(side, amt) {
  if (amt <= 0) return;
  const from = G.lp[side], to = Math.min(LP_MAX, from + amt); if (to === from) return;
  G.lp[side] = to;
  Sound.setDanger(G.lp.p > 0 && G.lp.p < LP_MAX * 0.3);
  UI.floatText($('#slot-' + side), '+' + (to - from), 'heal');
  const t0 = performance.now(), dur = RM ? 1 : AD(600);
  await new Promise(res => { const step = now => { const k = Math.min(1, (now - t0) / dur); UI.renderLP(side, from + (to - from) * k); k < 1 ? requestAnimationFrame(step) : res(); }; requestAnimationFrame(step); });
  await sleep(200);
}
function skillLine(m, who) { const sk = SKILLS[m.id]; return `<span class="who">${who}</span><b>【${esc(sk.name)}】</b>${esc(sk.text)}`; }

